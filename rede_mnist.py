import json
import numpy as np

def export_input_to_circom(model, filename="input.json"):
    """
    Extrai pesos e biases das camadas Dense do modelo para o formato JSON do Circom.
    Assume fator de escala 10.000 (10^4).
    """
    scale = 1000000

    # Extrair Pesos e Biases das Camadas Dense
    layers = [l for l in model.layers if isinstance(l, keras.layers.Dense)]

    def format_param(param):
        # Multiplica pelo fator de escala e converte para string de inteiro
        scaled = (param * scale).astype(int)
        return scaled.astype(str).tolist()

    # extraindo input para predição
    input_data = (x_test[0].flatten() * scale).astype(int).astype(str).tolist()
    predicted_class = int(np.argmax(model.predict(np.expand_dims(x_test[0], axis=0))))

    # Extrair Pesos e Biases
    weights_1 = format_param(layers[0].get_weights()[0].T) # Transposto para [saida][entrada]
    bias_1 = format_param(layers[0].get_weights()[1])

    weights_2 = format_param(layers[1].get_weights()[0].T)
    bias_2 = format_param(layers[1].get_weights()[1])

    weights_3 = format_param(layers[2].get_weights()[0].T)
    bias_3 = format_param(layers[2].get_weights()[1])

    # Montar o dicionário final
    model_params_dict = {
        "predicted_class": str(predicted_class),
        "in": input_data,
        "weights_1": weights_1,
        "bias_1": bias_1,
        "weights_2": weights_2,
        "bias_2": bias_2,
        "weights_3": weights_3,
        "bias_3": bias_3
    }

    print("P-B 1: ", model_params_dict.get("weights_1").__len__(), model_params_dict.get("bias_1").__len__())
    print("P-B 2: ", model_params_dict.get("weights_2").__len__(), model_params_dict.get("bias_2").__len__())
    print("P-B 3: ", model_params_dict.get("weights_3").__len__(), model_params_dict.get("bias_3").__len__())
    print("input_size: ", model_params_dict.get("in").__len__())
    print("predicted_class: ", model_params_dict.get("predicted_class").__len__())

    with open(filename, "w") as f:
        json.dump(model_params_dict, f)

# Exemplo de uso para exportar tudo separadamente
export_input_to_circom(model)

